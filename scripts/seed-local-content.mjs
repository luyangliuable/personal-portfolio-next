import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { MongoClient, ObjectId } from "mongodb";
import { blogs } from "./seed/blogs.mjs";
import { referencedImages } from "./seed/catalog.mjs";
import { blogMarkdown } from "./seed/markdown.mjs";
import { collectNotes } from "./seed/notes.mjs";
import { renderPdf, renderPng, seedId } from "./seed/render.mjs";

const AUTHOR = "Luyang Liu";
const uri = process.env.MONGOURI ?? "mongodb://localhost:27017";
const imageDir = path.resolve(
    process.env.IMAGE_STORE_LOCATION ?? ".local/images",
);
const postDir = path.resolve(
    process.env.MARKDOWN_POSTS_STORE_LOCATION ?? ".local/posts",
);
const notesDir = process.env.NOTES_STORE_LOCATION ?? null;
// Real copies of referenced images (<id>.<ext>) are used instead of placeholders.
const originalsDir = path.resolve(".local/originals");

// Shell exports win over --env-file, so never trust that uri points locally.
const host = new URL(uri.replace(/^mongodb(\+srv)?:/, "http:")).hostname;
if (!["localhost", "127.0.0.1", "::1"].includes(host)) {
    console.error(
        `Refusing to seed non-local MongoDB host "${host}". Unset MONGOURI ` +
            "in your shell or run `npm run seed`, which clears it first.",
    );
    process.exit(1);
}
console.log(
    `Seeding ${host} with images in ${imageDir}, posts in ${postDir}` +
        (notesDir ? ` and notes from ${notesDir}` : ""),
);

function rustDate(date) {
    return date.toISOString().replace(/\.\d+Z$/, "Z");
}

async function findOriginal(id) {
    const files = await readdir(originalsDir).catch(() => []);
    const name = files.find((file) => file.startsWith(`${id}.`));
    if (!name) return null;
    const file = await readFile(path.join(originalsDir, name));
    return { file, imageType: path.extname(name).slice(1) };
}

async function saveImage(db, image) {
    const original = await findOriginal(image.id);
    const isPdf = image.kind === "pdf";
    const imageType = original?.imageType ?? (isPdf ? "pdf" : "png");
    const file = original
        ? original.file
        : isPdf
          ? renderPdf([
                AUTHOR,
                "Placeholder resume generated by the local seed.",
            ])
          : await renderPng(image);
    await writeFile(path.join(imageDir, `${image.id}.${imageType}`), file);
    await db.collection("LocalImage").updateOne(
        { _id: new ObjectId(image.id) },
        {
            $set: {
                image_type: imageType,
                file_name: image.id,
                description: `${image.group}: ${image.label}`,
                source: "local seed",
            },
        },
        { upsert: true },
    );
}

async function upsert(db, collection, document) {
    await db
        .collection(collection)
        .updateOne({ _id: document._id }, { $set: document }, { upsert: true });
}

async function seedBlog(db, blog) {
    const id = blog.id ?? seedId(`post:${blog.slug}`);
    const [cover, ...figures] = ["cover", "figure-1", "figure-2"].map(
        (name, index) => ({
            id: seedId(`${name}:${blog.slug}`),
            group: index ? `Blog Figure ${index}` : "Blog Cover",
            label: blog.heading,
            kind: "banner",
        }),
    );
    for (const image of [cover, ...figures]) await saveImage(db, image);

    const year = blog.date.getUTCFullYear();
    const month = blog.date.getUTCMonth() + 1;
    const monthDir = path.join(postDir, String(year), String(month));
    await mkdir(monthDir, { recursive: true });
    const markdown = blogMarkdown(
        blog,
        figures.map((figure) => figure.id),
    );
    await writeFile(path.join(monthDir, `${blog.slug}.md`), markdown);

    const description = markdown.split("\n")[0];
    await upsert(db, "Post", {
        _id: new ObjectId(id),
        heading: blog.heading,
        author: AUTHOR,
        description,
        post_type: "blog",
        year,
        month,
        date_created: rustDate(blog.date),
        date_last_modified: rustDate(blog.date),
        file_name: blog.slug,
        tags: blog.tags,
        reading_time_minutes: blog.minutes,
        is_featured: blog.featured,
        in_progress: blog.inProgress,
        active: true,
        image: new ObjectId(cover.id),
        checksum: "local-seed",
        body: description,
    });
}

async function seedNotes(db) {
    if (!notesDir) return 0;
    const notes = await collectNotes(path.resolve(notesDir));
    const categories = [...new Set(notes.map((note) => note.category))];
    for (const category of categories)
        await saveImage(db, {
            id: seedId(`note-cover:${category}`),
            group: "Coding Notes",
            label: category,
            kind: "banner",
        });
    for (const note of notes)
        await upsert(db, "Note", {
            _id: new ObjectId(note.id),
            heading: note.heading,
            author: AUTHOR,
            description: `Notes on ${note.category}.`,
            date_created: rustDate(note.date),
            date_last_modified: rustDate(note.date),
            file_path: note.filePath,
            tags: [note.category],
            reading_time_minutes: note.minutes,
            active: true,
            image: new ObjectId(seedId(`note-cover:${note.category}`)),
            checksum: "local-seed",
            body: "",
        });
    // Drop notes seeded by earlier runs whose files are now gone or empty.
    await db.collection("Note").deleteMany({
        checksum: "local-seed",
        _id: { $nin: notes.map((note) => new ObjectId(note.id)) },
    });
    return notes.length;
}

const client = new MongoClient(uri);
await mkdir(imageDir, { recursive: true });
await client.connect();
try {
    const db = client.db("rustDB");
    for (const image of referencedImages) await saveImage(db, image);
    for (const blog of blogs) await seedBlog(db, blog);
    const noteCount = await seedNotes(db);
    console.log(
        `Seeded ${referencedImages.length} referenced images, ${blogs.length} posts ` +
            `and ${noteCount} notes${notesDir ? ` from ${notesDir}` : " (NOTES_STORE_LOCATION unset)"}.`,
    );
} finally {
    await client.close();
}
